const roadmapService = require('../services/roadmapService');
const asyncHandler = require('../utils/asyncHandler');

const getRoadmap = asyncHandler(async (req, res) => {
  const plan = await roadmapService.getLatestPlan(req.user.id);
  res.json({
    data: plan,
    meta: {
      ai_configured: roadmapService.isAiConfigured(),
      note: 'When AI is not configured, the roadmap is generated by a rule-based engine from your profile, target role and skill gaps.',
    },
  });
});

const generate = asyncHandler(async (req, res) => {
  const result = await roadmapService.generateRoadmap(req.user, req.body);
  res.status(201).json({
    data: result.plan,
    meta: {
      ...result.meta,
      note: 'Dates are editable. This is a preparation recommendation, not a guarantee of placement.',
    },
    message: result.meta.generated_by === 'ai' ? 'AI-assisted roadmap generated.' : 'Roadmap generated from your skill gaps.',
  });
});

const createTask = asyncHandler(async (req, res) => {
  const task = await roadmapService.createTask(req.user.id, req.body);
  res.status(201).json({ data: task, message: 'Roadmap task added.' });
});

const updateTask = asyncHandler(async (req, res) => {
  const task = await roadmapService.updateTask(req.user.id, req.params.id, req.body);
  res.json({ data: task, message: 'Roadmap task updated.' });
});

const deleteTask = asyncHandler(async (req, res) => {
  await roadmapService.deleteTask(req.user.id, req.params.id);
  res.json({ message: 'Roadmap task deleted.' });
});

module.exports = { getRoadmap, generate, createTask, updateTask, deleteTask };
